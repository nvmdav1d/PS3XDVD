#define GLYPH_W 5
#define GLYPH_H 7
#define ADVANCE 6

uint32_t COL_BG, COL_PANEL, COL_PANEL2, COL_LINE, COL_TEXT;
uint32_t COL_DIM, COL_ACCENT, COL_OK, COL_WARN, COL_ERR, COL_SEL;

static SDL_Surface *g_screen;
static uint32_t    *g_px;
static int          g_pitch_px;   /* screen->pitch / 4 */
static int          g_locked;

int gfx_init(void)
{
	if (SDL_Init(SDL_INIT_VIDEO) != 0)
		return -1;

	g_screen = SDL_SetVideoMode(GFX_W, GFX_H, 32, SDL_SWSURFACE);
	if (g_screen == NULL)
	{
		SDL_Quit();
		return -1;
	}

	if (g_screen->format->BytesPerPixel != 4)
	{
		SDL_Quit();
		return -1;
	}

	g_px       = (uint32_t *)g_screen->pixels;
	g_pitch_px = g_screen->pitch / 4;

	COL_BG     = SDL_MapRGB(g_screen->format,  16,  18,  24);
	COL_PANEL  = SDL_MapRGB(g_screen->format,  30,  34,  44);
	COL_PANEL2 = SDL_MapRGB(g_screen->format,  40,  46,  58);
	COL_LINE   = SDL_MapRGB(g_screen->format,  70,  80,  98);
	COL_TEXT   = SDL_MapRGB(g_screen->format, 232, 236, 244);
	COL_DIM    = SDL_MapRGB(g_screen->format, 138, 148, 166);
	COL_ACCENT = SDL_MapRGB(g_screen->format,  86, 156, 240);
	COL_OK     = SDL_MapRGB(g_screen->format,  90, 200, 130);
	COL_WARN   = SDL_MapRGB(g_screen->format, 232, 186,  80);
	COL_ERR    = SDL_MapRGB(g_screen->format, 236,  96,  96);
	COL_SEL    = SDL_MapRGB(g_screen->format,  52,  96, 176);

	return 0;
}

void gfx_quit(void)
{
	g_screen = NULL;
	g_px    = NULL;
	SDL_Quit();
}

void gfx_begin(void)
{
	if (g_screen == NULL)
		return;
	if (SDL_LockSurface(g_screen) == 0)
	{
		g_px       = (uint32_t *)g_screen->pixels;
		g_pitch_px = g_screen->pitch / 4;
		g_locked   = 1;
	}
}

void gfx_end(void)
{
	if (g_locked)
	{
		SDL_UnlockSurface(g_screen);
		g_locked = 0;
	}
	if (g_screen != NULL)
		SDL_Flip(g_screen);
}

void gfx_clear(uint32_t color)
{
	if (g_px == NULL)
		return;
	{
		int y;
		for (y = 0; y < GFX_H; y++)
		{
			uint32_t *row = g_px + (size_t)y * g_pitch_px;
			int x;
			for (x = 0; x < GFX_W; x++)
				row[x] = color;
		}
	}
}

void gfx_fill(int x, int y, int w, int h, uint32_t color)
{
	int yy;

	if (g_px == NULL || w <= 0 || h <= 0)
		return;
	if (x < 0) { w += x; x = 0; }
	if (y < 0) { h += y; y = 0; }
	if (x + w > GFX_W)  w = GFX_W - x;
	if (y + h > GFX_H)  h = GFX_H - y;
	if (w <= 0 || h <= 0)
		return;

	for (yy = y; yy < y + h; yy++)
	{
		uint32_t *row = g_px + (size_t)yy * g_pitch_px + x;
		int xx;
		for (xx = 0; xx < w; xx++)
			row[xx] = color;
	}
}

void gfx_hline(int x, int y, int w, uint32_t color)
{
	gfx_fill(x, y, w, 1, color);
}

void gfx_vline(int x, int y, int h, uint32_t color)
{
	gfx_fill(x, y, 1, h, color);
}

void gfx_frame(int x, int y, int w, int h, uint32_t color)
{
	if (w <= 0 || h <= 0)
		return;
	gfx_hline(x, y, w, color);
	gfx_hline(x, y + h - 1, w, color);
	gfx_vline(x, y, h, color);
	gfx_vline(x + w - 1, y, h, color);
}

int gfx_text_w(const char *s, int scale)
{
	if (s == NULL)
		return 0;
	/* trailing blanks are not worth width */
	{
		size_t n = strlen(s);
		while (n > 0 && s[n - 1] == ' ')
			n--;
		return (int)n * ADVANCE * scale;
	}
}

int gfx_text_h(int scale)
{
	return GLYPH_H * scale;
}

void gfx_text(int x, int y, uint32_t color, const char *s, int scale)
{
	int cx = x;

	if (g_px == NULL || s == NULL || scale < 1)
		return;

	for (; *s != '\0'; s++)
	{
		unsigned char ch = (unsigned char)*s;
		const uint8_t *g;

		if (ch < 0x20 || ch > 0x7E)
			ch = '?';
		g = font5x7[ch - 0x20];

		{
			int col;
			for (col = 0; col < GLYPH_W; col++)
			{
				uint8_t bits = g[col];
				int row;
				for (row = 0; row < GLYPH_H; row++)
				{
					if (bits & (1u << row))
						gfx_fill(cx + col * scale, y + row * scale, scale, scale, color);
				}
			}
		}
		cx += ADVANCE * scale;
		if (cx >= GFX_W)
			break;
	}
}

void gfx_text_box(int x, int y, int w, int h, uint32_t color, const char *s,
                  int scale, int align)
{
	int tw = gfx_text_w(s, scale);
	int th = GLYPH_H * scale;
	int tx = x;
	int ty = y + (h - th) / 2;

	if (w <= 0)
		w = GFX_W;

	if (align == ALIGN_CENTER)
		tx = x + (w - tw) / 2;
	else if (align == ALIGN_RIGHT)
		tx = x + w - tw;

	gfx_text(tx, ty, color, s, scale);
}

void gfx_bar(int x, int y, int w, int h, float frac, uint32_t bg, uint32_t fg)
{
	int fill;

	gfx_fill(x, y, w, h, bg);
	gfx_frame(x, y, w, h, COL_LINE);

	if (frac < 0.0f)  frac = 0.0f;
	if (frac > 1.0f)  frac = 1.0f;

	fill = (int)((float)w * frac);
	if (fill > w - 2)
		fill = w - 2;
	if (fill > 0)
		gfx_fill(x + 1, y + 1, fill, h - 2, fg);
}
